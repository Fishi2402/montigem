package coveragedashboard.commands;

import coveragedashboard.CoverageDashboardManager;
import coveragedashboard.CoverageModule;
import coveragedashboard.CoveragePerspective;
import coveragedashboard.CoverageSourceFile;
import coveragedashboard.TemplateUsage;
import coveragedashboard.TemplateUsageBuilder;
import jsweet.lang.Erased;
import umlp.backendrte.command.ListResult;
import umlp.jsweet.extension.annotation.BackendOnly;
import umlp.jsweet.extension.annotation.BackendOnlyModes;

import java.util.ArrayList;
import java.util.HashSet;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Optional;
import java.util.Set;

public class GetTemplateUsages extends GetTemplateUsagesTOP {

  public GetTemplateUsages(long template, long directPerspective) {
    super(template, directPerspective);
  }

  @Override
  public ListResult<TemplateUsage, List<TemplateUsage>> doAction(){
    Optional<List<TemplateUsage>> result = getTemplateUsages(this.getTemplateGemId(), this.getDirectPerspectiveGemId());
    if(result.isEmpty())
      return ListResult.error(
          getId(), TemplateUsage.class.getName());
    return ListResult.of(getId(), result.get(), TemplateUsage.class.getName());
  }

  @BackendOnly(BackendOnlyModes.THROW_ERROR)
  protected Optional<List<TemplateUsage>> getTemplateUsages(long template, long directPerspective){
    Optional<CoverageSourceFile> templateOpt = CoverageDashboardManager.coverageSourceFileOpt(template);
    if(templateOpt.isEmpty())
      return Optional.empty();
    Optional<CoveragePerspective> perspectiveOpt = CoverageDashboardManager.coveragePerspectiveOpt(directPerspective);
    if(perspectiveOpt.isEmpty())
      return Optional.empty();

    List<TemplateUsage> usages = new ArrayList<>();
    collectUsages(templateOpt.get(), perspectiveOpt.get().getRootModule(), usages);
    return Optional.of(usages);
  }

  @Erased
  private void collectUsages(CoverageSourceFile template, CoverageModule module, List<TemplateUsage> usages){
    if(module == null)
      return;

    Set<CoverageSourceFile> visited = new HashSet<>();
    Set<Long> visitedTargetIds = new HashSet<>();
    List<CoverageSourceFile> currentChain = new ArrayList<>();
    collectFromModule(template, module, currentChain, visited, visitedTargetIds, usages);
  }

  @Erased
  private void collectFromModule(
        CoverageSourceFile template,
        CoverageModule module,
        List<CoverageSourceFile> currentChain,
        Set<CoverageSourceFile> visited,
        Set<Long> visitedTargetIds,
        List<TemplateUsage> usages){
    if(module == null)
      return;

    for(CoverageSourceFile file : module.getSourceFilesList())
      traverseAndFindUsage(file, template, currentChain, visited, visitedTargetIds, usages);

    for(CoverageModule subModule : module.getSubModulesList())
      collectFromModule(template, subModule, currentChain, visited, visitedTargetIds, usages);
  }

  @Erased
  private void traverseAndFindUsage(
        CoverageSourceFile current,
        CoverageSourceFile template,
        List<CoverageSourceFile> currentChain,
        Set<CoverageSourceFile> visited,
        Set<Long> visitedTargetIds,
        List<TemplateUsage> usages){
    if(current == null || !visited.add(current) || current.getGeneratedByList() == null){
      return;
    }

    // push to current path
    currentChain.add(current);
    for(CoverageSourceFile source : current.getGeneratedByList()) {
      if(matches(template, source)){
        // current was directly generated by template
        if(visitedTargetIds.add(current.getGemId())){
          TemplateUsageBuilder builder = CoverageDashboardManager.templateUsageBuilder()
              .targetFile(current)
              .chain(currentChain);

          builder.build().ifPresent(usages::add);
        }
      }
      traverseAndFindUsage(source, template, currentChain, visited, visitedTargetIds, usages);
    }
    // pop during backtracking
    currentChain.remove(currentChain.size() - 1);
  }

  @Erased
  private boolean matches(CoverageSourceFile template, CoverageSourceFile source) {
    return template.getPath().replace("\\", "/").equals(source.getPath().replace("\\", "/"));
  }
}
