package umlp.py.printer;

import de.monticore.prettyprint.IndentPrinter;
import de.monticore.types.mcsimplegenerictypes._prettyprint.MCSimpleGenericTypesPrettyPrinter;

public class PythonMYSimpleGenericTypesPrinter extends MCSimpleGenericTypesPrettyPrinter {
  public PythonMYSimpleGenericTypesPrinter(IndentPrinter printer, boolean printComments) {
    super(printer, printComments);
  }

  @Override
  public void handle(de.monticore.types.mcsimplegenerictypes._ast.ASTMCBasicGenericType node) {
    if (this.isPrintComments()) {
      de.monticore.prettyprint.CommentPrettyPrinter.printPreComments(node, getPrinter());
    }
    java.util.Iterator<de.monticore.types.mccollectiontypes._ast.ASTMCTypeArgument> iter_mCTypeArgument = node.getMCTypeArgumentList().iterator();
    java.util.Iterator<String> iter_name = node.getNameList().iterator();
    if (iter_name.hasNext()) { // opt: 2 req: 1
      if (iter_name.hasNext()) { // opt: 1 req: 1
        getPrinter().print(iter_name.next() + " ");
        while (iter_name.hasNext()) { // While single alt
          getPrinter().stripTrailing();
          getPrinter().print(".");
          getPrinter().print(iter_name.next() + " ");
        }
      }

      getPrinter().stripTrailing();
      getPrinter().print("[");

      if (iter_mCTypeArgument.hasNext()) { // opt: 1 req: 1
        iter_mCTypeArgument.next().accept(getTraverser());
        while (iter_mCTypeArgument.hasNext()) { // While single alt
          getPrinter().stripTrailing();
          getPrinter().print(",");

          iter_mCTypeArgument.next().accept(getTraverser());
        }
      }
      /* generated by template _prettyprinter.pp.Terminal*/
      getPrinter().stripTrailing();
      getPrinter().print("]");
    }

    if (this.isPrintComments()) {
      de.monticore.prettyprint.CommentPrettyPrinter.printPostComments(node, getPrinter());
    }

  }

}
