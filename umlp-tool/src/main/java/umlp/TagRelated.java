/**
 * Currently tags are used to exchange information given in class diagrams
 * (such as <code><<singleton>></code> StereoTypes on classes)
 * <p>
 * This stereotype information is then copied into a tags file,
 * which is then loaded again during the Gui-generation tasks.
 */
public class TagRelated {

  // We use the Symtab cmd option here to store our tagmodels
  public static void doStoreTagStereos(ASTCDCompilationUnit ast, UMLPTool tool, IUMLPArtifactScope symbolTable, CommandLine cmd) {
    // Extract singleton stereotypes and store them ina
    ASTTagUnit tagUnit = TagRepository.loadTempTagModel(ast.getCDDefinition().getName()).get();
    boolean[] hasTags = new boolean[1];
    UMLPTraverser traverser = UMLPMill.inheritanceTraverser();
    SimpleSymbolTagger tagger = new SimpleSymbolTagger(() -> Collections.singleton(tagUnit));
    traverser.add4CDBasis(new CDBasisVisitor2() {
      @Override
      public void visit(ASTCDClass node) {
        if (node.getModifier().isPresentStereotype() && node.getModifier().getStereotype().contains("singleton")) {
          ASTTag astTag = TagsMill.simpleTagBuilder().setName("singleton").build();
          hasTags[0] = true;
          tagger.addTag(node.getSymbol(), astTag);
          node.getCDMethodList().forEach(m -> {
            ASTTag astTagCommand = TagsMill.simpleTagBuilder().setName("command").build();
            tagger.addTag(m.getSymbol(), astTagCommand);
            hasTags[0] = true;
          });
        }
        if (node.getModifier().isDerived()) {
          ASTTag astTag = TagsMill.simpleTagBuilder().setName("derived").build();
          hasTags[0] = true;
          tagger.addTag(node.getSymbol(), astTag);
        }
      }
    });
    ast.accept(traverser);

    String s = UMLPToolOptions.SYMTAB.getValue(cmd);
    if (s != null && !s.isEmpty()) {
      // store tag file to passed file
      String pn = Names.getPathFromPackage(symbolTable.getPackageName());
      Path tagPath = Paths.get(
          s + (pn.isEmpty() ? "" : (File.separator
              + Names.getPathFromPackage(symbolTable.getPackageName())))
              + File.separator
              + symbolTable.getName()
              + ".tags");
      tagUnit.add_PreComment(new Comment("/* This file is automatically generated for " + ast.getCDDefinition().getName() + " */"));
      tool.print(TagsMill.prettyPrint(tagUnit, true), tagPath.toString());
      Reporting.reportFileCreation(tagPath.toString());

      TagRepository.unloadTagModel(tagUnit);
      try {
        TagRepository.loadTagModel(tagPath.toFile());
      } catch (IOException ignored) {}
    } else {
      System.out.println(TagsMill.prettyPrint(tagUnit, true));
      if (hasTags[0])
        Log.error("symboltable option is required to store tag information");
    }
  }


  public static void postInfo() {
    System.out.println("Finished usage of tags: Had " + Iterables.size(TagRepository.getLoadedTagUnits()) + " tag units");
    for (ASTTagUnit tagUnit : TagRepository.getLoadedTagUnits()) {
      System.out.println(" -tag: " + tagUnit.getName() + ": #" + tagUnit.getTagsList().size());
    }
  }

  public static void initLookup(MCPath importedSymbolPath) {
    System.out.println("Init tag lookup: " + importedSymbolPath.getEntries().size() + "(" + Iterables.size(TagRepository.getLoadedTagUnits()) + ") in " + importedSymbolPath.getEntries());
    TagRepository.clearTags(); // Make sure to unload all previous tags from earlier runs
    Set<File> tagFiles = importedSymbolPath.getEntries().stream()
        .map(x -> x.toFile().listFiles(f -> f.getName().endsWith(".tags")))
        .filter(Objects::nonNull)
        .flatMap(Arrays::stream)
        .peek(p -> System.out.println("Looking for tags within " + p.getAbsolutePath()))
        .collect(Collectors.toSet());

    // note: The generic Tags language does not support concrete UMLP syntax tagging
    TagsMill.init();

    if (!tagFiles.isEmpty()) {
      for (File f : tagFiles) {
        try {
          Optional<ASTTagUnit> opt = TagRepository.loadTagModel(f);
          if (opt.isEmpty()) {
            Log.error("Failed to load tag file " + f.getName() + " : parser error");
          } else if (opt.get().get_PreCommentList().isEmpty()) {
            Log.error("Comment missing in tag file " + f.getName());
          }
        } catch (IOException ioException) {
          Log.error("Failed to load tag file " + f.getName() + " :" + ioException.getMessage(), ioException);
        }
      }
      System.out.println("Finished tag lookup: Loaded " + Iterables.size(TagRepository.getLoadedTagUnits()) + " tag units");
      for (ASTTagUnit tagUnit : TagRepository.getLoadedTagUnits()) {
        System.out.println(" -tag: " + tagUnit.getName() + ": #" + tagUnit.getTagsList().size());
      }

    }

    importedSymbolPath.getEntries().stream()
        .filter(x -> x.getFileName().toString().contains(".jar"))
        .forEach(p -> {
          Reporting.reportOpenInputFile(p.toString());
          try (ZipFile zipFile = new ZipFile(p.toFile())) {
            Enumeration<? extends ZipEntry> zipEntries = zipFile.entries();
            while (zipEntries.hasMoreElements()) {
              ZipEntry entry = zipEntries.nextElement();
              if (entry.getName().endsWith(".tags")) {
                try (InputStreamReader reader = new InputStreamReader(zipFile.getInputStream(entry))) {
                  Optional<ASTTagUnit> opt = TagsMill.parser().parse(reader);
                  if (opt.isEmpty()) {
                    Log.error("Failed to load tag file " + p + entry.getName() + " : parser error");
                  } else if (opt.get().get_PreCommentList().isEmpty()) {
                    Log.error("Comment missing in tag file " + p + entry.getName());
                  } else {
                    Log.trace("Loaded tags from jar " + p + ":" + entry.getName(), "Tag");
                    var tag = TagRepository.loadTempTagModel(p + ":" + entry.getName());
                    tag.get().addAllTags(opt.get().getTagsList());
                  }

                }
              }
            }
          } catch (IOException e) {
            Log.error("Failed to load tags from " + p, e);
            throw new RuntimeException(e);
          }
        });

  }

}
