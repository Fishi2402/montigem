package umlp.generator.gui.decorator;

import de.monticore.cdbasis._ast.ASTCDClass;
import de.monticore.expressions.commonexpressions._ast.ASTCallExpression;
import de.monticore.generating.templateengine.GlobalExtensionManagement;
import de.monticore.guidsl._ast.ASTGUICompilationUnit;
import de.monticore.guidsl._ast.ASTGUIComponent;
import de.monticore.guidsl._prettyprint.GUIDSLFullPrettyPrinter;
import de.monticore.prettyprint.IndentPrinter;
import de.se_rwth.commons.StringTransformations;
import umlp.generator.gui.GUIGeneratorUtil;

public class EventDecorator extends GUIComponentDecorator {

  public EventDecorator(final GlobalExtensionManagement glex, ASTGUICompilationUnit guiAst) {
    super(glex, guiAst);
  }

  @Override
  public void transform(ASTCDClass decoratedClass, ASTGUIComponent guiComponent, String componentName) {
    GUIGeneratorUtil.getEventArguments(guiComponent).forEach(click -> {
      if (click.getGUIArgValue().isPresentExpression()
          && click.getGUIArgValue().getExpression() instanceof ASTCallExpression) {

        ASTCallExpression call = (ASTCallExpression) click.getGUIArgValue().getExpression();
        String buttonText = getButtonText(call); //  TODO

        if (isNavigateComponent(call)) {
          ASTGUIComponent arg = (ASTGUIComponent) call.getArguments().getExpressionList().get(0);
          getCD4C().addMethod(decoratedClass, "umlp.gui2java.NavigateEvent",
              // LEFT_CLICK + buttonText.replaceAll("\\s+", ""),
              click.getName() + guiComponent.getName() + componentName,
              arg.getName());
        }

        else {
          getCD4C().addMethod(decoratedClass, "umlp.gui2java.Event",
              //LEFT_CLICK + buttonText.replaceAll("\\s+", ""),
              /* public  Runnable leftClickButtonComp5 () {/* generated by template umlp.gui2java.Event*//*
                   return () -> pBuilder.decreaseAge(); }*/
              click.getName() + guiComponent.getName() + componentName,
              new GUIDSLFullPrettyPrinter(new IndentPrinter()).prettyprint(call));
        }
      }
    });

  }

  protected String getButtonText(ASTCallExpression call) {
    return StringTransformations.capitalize(guiDSLPrinter.prettyprint(call.getExpression()).replaceAll("\\.", "")
        .replaceAll("\"", ""));
  }

}
